
number_of_day = int(input("enter a number of days between 1 to 7"))
if number_of_day == 1:
    print("monday")
elif number_of_day == 2:
    print("tuesday")
elif number_of_day == 3:
    print("wednesday")
elif number_of_day == 4:
    print("thursday")
elif number_of_day == 5:
    print("friday")
elif number_of_day == 6:
    print("saturday")
elif number_of_day == 7:
    print("sunday")
else:
    print("enter valid number")
        
        